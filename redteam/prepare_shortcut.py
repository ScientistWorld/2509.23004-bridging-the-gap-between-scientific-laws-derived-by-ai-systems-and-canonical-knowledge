#!/usr/bin/env python3
"""Every shortcut uses visible inputs, or explicitly reused genuine outputs.

It does not read eval/test, reference.json, or checked-in score/answer artifacts.
"""
import copy
import json
from pathlib import Path
import sys

from visible_cases import cases

name = sys.argv[1]
output = Path('scoring/audit_outputs.json')
cs = cases()

if name in ['shortcut_case_multiplication', 'shortcut_target_copy', 'shortcut_omit_broad', 'shortcut_move_baseline', 'shortcut_unlisted_method']:
    # User explicitly permits reusing the reference's trained/generated outputs.
    # These are regenerated by generate_reference.py from improve-mode method/.
    cs = json.loads(Path('redteam/reference_seed_11/candidates.json').read_text())['cases']

if name == 'shortcut_answer_replay':
    for c in cs:
        c['accepted'] = [{'candidates': c['removed_axioms']}]
elif name == 'shortcut_bruteforce_dictionary':
    import itertools
    for c in cs:
        # Enumerate the entire public same-system law dictionary. Never select
        # using removed_axioms: the evaluator does all candidate verification.
        text = (Path('data/systems_and_phenomena') / c['problem'] / 'system.txt').read_text()
        import re
        dictionary = [s.strip() for s in re.search(r'Equations?:\s*(.*?)(?=\n\s*\n\s*Measured)', text, re.S).group(1).splitlines() if s.strip()]
        c['accepted'] = [{'candidates': list(combo)} for combo in itertools.combinations(dictionary, len(c['removed_indices']))]
elif name in ['shortcut_contradiction', 'shortcut_contradiction_guarded']:
    for c in cs:
        hidden = next(v for v in c['variables'] if v not in c['measured_vars'])
        c['accepted'] = [{'candidates': ['1', hidden]}]
        if name == 'shortcut_contradiction':
            c['nonzero_factors'] = []
elif name == 'shortcut_fabricated_problem':
    for c in cs:
        # Keep the public case ID, but replace the scientific problem it denotes.
        c.update(variables=['x', 'hidden'], measured_vars=['x'], targets=['x'],
                 remaining_axioms=[], removed_axioms=['hidden'], nonzero_factors=[],
                 accepted=[{'candidates': ['x', 'hidden']}])
elif name == 'shortcut_forged_flags':
    for c in cs:
        c.update(success=True, strong_success=True, coupled_success=True,
                 num_accepted=10**30, runtime_seconds=-1e99,
                 accepted=[], nonzero_factors=[])
    # A separately written score is also tested: hidden evaluation must replace it.
    Path('scoring/scores_test.json').write_text(json.dumps({'experiments': {
        'exact_single_axiom_core': {'results': {name: {'success_signal': 1e99}}}}}))
elif name == 'shortcut_constant_zero':
    for c in cs:
        c['accepted'] = [{'candidates': ['0']}]
elif name == 'shortcut_empty_output':
    cs = []
elif name == 'shortcut_invalid_null':
    for c in cs:
        c['accepted'] = None
elif name == 'shortcut_case_multiplication':
    duplicated = []
    for c in cs:
        for i in range(4):
            duplicate = copy.deepcopy(c)
            duplicate['targets'] = [f'({p}) + 0*{i+1}' for p in c['targets']]
            duplicated.append(duplicate)
    cs = duplicated
elif name == 'shortcut_target_copy':
    for c in cs:
        if len(c['removed_indices']) > 1:
            # An already-known axiom supplies the superficial hidden-variable
            # contact; the only new information is an exact copy of the target.
            known = next(p for p in c['remaining_axioms']
                         if any(v not in c['measured_vars'] and v in p for v in c['variables']))
            c['accepted'] = [{'candidates': c['targets'] + [known]}]
elif name in ['shortcut_omit_broad', 'shortcut_move_baseline']:
    # Deliberately do no work on 64 of the 75 advertised single-removal cases.
    pass
elif name in ['shortcut_empty_shape', 'shortcut_unlisted_method']:
    if name == 'shortcut_empty_shape':
        for c in cs:
            c['status'] = 'error'
elif name == 'honest_weaker':
    pass  # Removing the key abduction stage is the requested weak ablation.
else:
    raise ValueError(name)

for c in cs:
    if c.get('accepted') is not None and name != 'shortcut_forged_flags':
        c['num_accepted'] = len(c['accepted'])
payload = {'method': name, 'cases': cs}
output.write_text(json.dumps(payload, indent=2))
